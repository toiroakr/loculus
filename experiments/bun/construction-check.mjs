import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { cpus } from 'node:os';
const hash = path => createHash('sha256').update(readFileSync(path)).digest('hex');
const bun = process.env.BUN_BIN ?? 'bun';
const baseline = process.env.BASELINE_DIR ?? '/tmp/loculus-bun-before-construction';
const report = { date: new Date().toISOString(), sourceHash: hash('src/index.ts'), distHash: hash('dist/index.js'), cpu: cpus()[0].model, unit: 'microseconds per schema construction plus one valid validation', warmup: 100, iterations: 500, bun: spawnSync(bun, ['--version'], { encoding: 'utf8' }).stdout.trim(), node: process.version, rounds: 7, processes: 9, cases: {} };
const summary = samples => { const sorted = [...samples].sort((a,b)=>a-b); return { median: sorted[Math.floor(sorted.length/2)], min: sorted[0], max: sorted.at(-1), samples }; };
const cases = ['strings-3', 'strings-30', 'cli'].flatMap(profile => ['before', 'after', 'valibot'].flatMap(kind => ['node','bun'].map(runtime => ({profile,kind,runtime,file: resolve(kind === 'before' ? baseline : 'experiments/bun/generated', `${kind === 'valibot' ? 'valibot' : 'loculus'}-${profile}.mjs`)}))));
for (const c of cases) report.cases[`${c.profile}/${c.kind}/${c.runtime}`] = { samples: [], probes: undefined, fixtureHash: hash(c.file) };
for (let pass=0;pass<report.processes;pass++) for(const c of cases.slice(pass%cases.length).concat(cases.slice(0,pass%cases.length))) {
  const result=spawnSync(c.runtime==='node'?process.execPath:bun,[c.file,'construct'],{encoding:'utf8',timeout:30000});
  assert.equal(result.status,0,result.stderr);
  const rows=result.stdout.trim().split('\n').map(line=>JSON.parse(line));
  const entry=report.cases[`${c.profile}/${c.kind}/${c.runtime}`];
  const probes=rows.filter(row=>row.kind==='probe');
  if(entry.probes) assert.deepEqual(probes,entry.probes); else entry.probes=probes;
  const rounds=rows.filter(row=>row.kind==='bench');
  assert.equal(rounds.length,7);
  for(const row of rounds) assert.equal(row.sink,(100+(row.round+1)*500)*Object.keys(probes[0].value).length);
  entry.samples.push(...rounds.map(row=>row.elapsedMs*1000/row.iterations));
}
for (const entry of Object.values(report.cases)) Object.assign(entry,summary(entry.samples));
for(const profile of ['strings-3','strings-30','cli']) for(const runtime of ['node','bun']) assert.deepEqual(report.cases[`${profile}/before/${runtime}`].probes,report.cases[`${profile}/after/${runtime}`].probes);
report.completed=true;
writeFileSync('experiments/bun/construction-results.json',JSON.stringify(report,null,2)+'\n');
for(const [name,c]of Object.entries(report.cases)) console.log(name,c.median.toFixed(3),'µs');
