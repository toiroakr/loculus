import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(resolve('docs/performance-tuning.html')).href);
 assert.equal(await page.locator('#build-time').count(),1);
 assert.equal(await page.locator('#bt-speed tbody tr').count(),64);
 assert.equal(await page.locator('#bt-bundles tbody tr').count(),107);
 assert.equal(await page.locator('#bt-details').evaluate(e=>e.open),false);
 assert.match(await page.locator('#bt-scopes + pre').innerText(),/loculus\/rolldown/);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'bench/build-time/generated/report-mobile.png'});
 await page.locator('a[href="#bt-details"]').first().click();
 await page.waitForFunction(()=>document.getElementById('bt-details').open);
 assert.equal(await page.locator('#bt-details').evaluate(e=>e.open),true);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.locator('#bt-speed a[href="#case-scalar-string-basic"]').first().click();
 const schema=page.locator('#case-scalar-string-basic');
 await schema.locator('pre').first().waitFor({state:'visible'});
 assert.equal(await schema.locator('h3').count(),3);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.setViewportSize({width:1280,height:900});
 await page.goto(pathToFileURL(resolve('docs/performance-tuning.html')).href);
 assert.equal(await page.locator('#bt-details').evaluate(e=>e.open),false);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'bench/build-time/generated/report-desktop.png'});
 assert.deepEqual(errors,[]);
 console.log('Verified build-time section, all rows, original code links, source example, mobile and desktop.');
}finally{await browser.close();}
