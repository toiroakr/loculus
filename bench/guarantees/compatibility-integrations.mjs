import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {standardSchemaResolver} from '@hookform/resolvers/standard-schema';
import * as l from '../../dist/index.js';

assert.ok(process.argv[2], 'Pass the Politty checkout path');
const root = resolve(process.argv[2]);
const {arg, defineCommand, runCommand} = await import(pathToFileURL(resolve(root, 'packages/loculus/src/index.ts')).href);
const {getArgMeta} = await import(pathToFileURL(resolve(root, 'packages/core/src/core/arg-registry.ts')).href);
const {extractLoculusFields, loculusAdapter} = await import(pathToFileURL(resolve(root, 'packages/loculus/src/adapter.ts')).href);

const first = arg(l.string(), {alias: 'a', description: 'First'});
const second = arg(l.string(), {alias: 'b', description: 'Second'});
assert.notEqual(first, second);
assert.equal(getArgMeta(first).alias, 'a');
assert.equal(getArgMeta(second).alias, 'b');
const args = l.object({port: arg(l.number({integer: true, gte: 1, default: 3000}), {alias: 'p'}), name: first, mode: l.enum(['a', 'b'], {optional: true})});
const fields = extractLoculusFields(args).fields;
assert.equal(fields.find(field => field.name === 'name').required, true);
assert.equal(fields.find(field => field.name === 'port').defaultValue, 3000);
const command = defineCommand({name: 'compatibility', args, run: parsed => parsed});
assert.equal(loculusAdapter.getUnknownKeysMode(args), 'strict');
const cli = await runCommand(command, ['--name', 'guest', '-p', '42', '--mode', 'a']);
assert.equal(cli.success, true);
assert.deepEqual(cli.result, {port: 42, name: 'guest', mode: 'a'});
const cliDefault = await runCommand(command, ['--name', 'guest']);
assert.equal(cliDefault.success, true);
assert.deepEqual(cliDefault.result, {port: 3000, name: 'guest'});
const cliUnknown = await runCommand(command, ['--name', 'guest', '--typo', 'value']);
assert.equal(cliUnknown.success, false);
const inherited = loculusAdapter.validate(Object.create({port: '42', name: 'guest'}), args);
assert.deepEqual(inherited, {success: true, data: {port: 42, name: 'guest'}});

const variant = l.discriminatedUnion('kind', [l.object({kind: l.literal('a'), a: l.number()}), l.object({kind: l.literal('b'), b: l.string()})]);
const branch = defineCommand({name: 'variant', args: variant, run: parsed => parsed});
const cliVariant = await runCommand(branch, ['--kind', 'a', '--a', '2']);
assert.equal(cliVariant.success, true);
assert.deepEqual(cliVariant.result, {kind: 'a', a: 2});

const form = l.object({title: l.string({min: 1}), items: l.array(l.object({name: l.string({min: 1}), quantity: l.number({integer: true, gte: 1})}), {wrapScalar: false, min: 1})});
const resolver = standardSchemaResolver(form);
const resolverOptions = {criteriaMode: 'all', fields: {}, shouldUseNativeValidation: false};
const rhf = await resolver({title: 'Order', items: [{name: 'A', quantity: '2'}]}, undefined, resolverOptions);
assert.deepEqual(rhf, {values: {title: 'Order', items: [{name: 'A', quantity: 2}]}, errors: {}});
const rhfErrors = await resolver({title: '', items: [{name: '', quantity: '0'}]}, undefined, resolverOptions);
assert.deepEqual(rhfErrors.values, {});
assert.ok(rhfErrors.errors.title);
assert.ok(rhfErrors.errors.items[0].name);
assert.ok(rhfErrors.errors.items[0].quantity);
writeFileSync('bench/guarantees/compatibility-integrations.json', JSON.stringify({completed: true, cli, cliDefault, cliUnknown, cliVariant, inherited, fields, rhf, rhfErrors, polittyRoot: root}, null, 2) + '\n');
console.log('Verified current Loculus with actual Politty commands, registry, adapter and RHF resolver');
