import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const read = name => JSON.parse(readFileSync(`bench/optimization-3/${name}.json`));
const count = report => Object.values(report.cases).filter(c => c.library === 'loculus' && c.version === 'after').length;
const ordinary = count(read('settled-results'));
const compiled = count(read('compiled-settled-results'));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(resolve('docs/performance-tuning.html')).href);
  assert.equal(await page.locator('#speed tbody tr').count(), ordinary * 6 + compiled * 4);
  assert.equal(await page.locator('.additional-speed tbody tr').count(), 60);
  assert.equal(await page.locator('#speed tbody tr[data-scope="compile"][data-mode="construct"]').count(), 0);
  assert.equal(await page.locator('summary').filter({ hasText: ' — ' }).count(), 110);
  assert.equal(await page.locator('.scenario').count(), 12);
  assert.equal(await page.locator('#evidence').evaluate(element => element.open), false);
  assert.equal(await page.locator('#speed').isVisible(), false);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'bench/optimization-3/generated/report-mobile.png' });
  await page.locator('a[href="#valibot-analysis"]').click();
  assert.equal(await page.locator('#valibot-analysis').isVisible(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'bench/optimization-3/generated/report-valibot-mobile.png' });
  await page.locator('a[href="#cli-cases"]').click();
  assert.equal(await page.locator('.cli-scenario').count(), 4);
  assert.equal(await page.locator('[id^="case-cli-wrangler-"]').count(), 0);
  assert.equal(await page.locator('#case-cli-cf-deploy-full').count(), 1);
  assert.equal(await page.locator('#case-cli-cf-dns-records-list-full').count(), 1);
  assert.equal(await page.locator('.cli-speed tbody tr').count(), 80);
  assert.equal(await page.locator('.cli-bundles tbody tr').count(), 16);
  assert.equal(await page.locator('.cli-speed tr[data-scope="compile"][data-mode="construct"]').count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'bench/optimization-3/generated/report-cli-mobile.png' });
  await page.locator('a[href="#case-cli-cf-dns-records-list-full"]').click();
  await page.locator('#case-cli-cf-dns-records-list-full pre code').first().waitFor({ state: 'visible' });
  assert.equal(await page.locator('#case-cli-cf-dns-records-list-full').evaluate(element => element.open), true);
  assert.equal(await page.locator('#case-cli-cf-dns-records-list-full h3').count(), 3);
  assert.equal(await page.locator('#case-cli-cf-dns-records-list-full pre code').count(), 4);
  await page.locator('a[href="#case-width-100"]').first().click();
  await page.locator('#case-width-100 pre code').first().waitFor({ state: 'visible' });
  assert.equal(await page.locator('#evidence').evaluate(element => element.open), true);
  assert.equal(await page.locator('#case-width-100').evaluate(element => element.open), true);
  assert.equal(await page.locator('#case-width-100 pre code').count(), 4);
  await page.selectOption('#runtime', 'bun');
  await page.selectOption('#scope', 'compile');
  assert.deepEqual(errors, []);
  assert.equal(await page.locator('#mode option[value="construct"]').evaluate(option => option.disabled), true);
  await page.selectOption('#mode', 'invalid');
  assert.equal(await page.locator('#speed tbody tr:visible').count(), compiled);
  const code = page.locator('#case-string-basic');
  await code.locator('summary').click();
  assert.equal(await code.locator('pre code').count(), 4);
  assert.deepEqual(errors, []);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(pathToFileURL(resolve('docs/performance-tuning.html')).href);
  assert.equal(await page.locator('#evidence').evaluate(element => element.open), false);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'bench/optimization-3/generated/report-desktop.png' });
  assert.deepEqual(errors, []);
  console.log('Scenario summaries, closed appendix, code links, mobile/desktop layout, filters and JavaScript errors verified.');
} finally { await browser.close(); }
