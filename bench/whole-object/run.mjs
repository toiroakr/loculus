import {readFileSync,writeFileSync} from 'node:fs';
const arg=name=>process.argv.find(x=>x.startsWith(name+'='))?.slice(name.length+1);
const passes=Number(arg('--processes')??11);
const output=arg('--output')??'bench/whole-object/settled-results.json';
let source=readFileSync('bench/build-time/run.mjs','utf8');
source=source.replaceAll('bench/build-time','bench/whole-object');
source=source.replace('freshProcesses:9',`freshProcesses:${passes}`);
source=source.replace('pass<9',`pass<${passes}`);
source=source.replace("'/ 9'",`'/ ${passes}'`);
source=source.replace('warmupMilliseconds:30','warmupMilliseconds:30,warmupOverrides:{"width-100":500}');
source=source.replaceAll("['construct','valid']","['construct','valid','invalid']");
source=source.replaceAll('bench/whole-object/settled-results.json',output);
source=source.replaceAll('bench/whole-object/settled-results.partial.json',output.replace(/\.json$/,'.partial.json'));
if(arg('--ids'))source=source.replace('bundles.cases.filter(c=>c.timed)',`bundles.cases.filter(c=>c.timed&&${JSON.stringify(arg('--ids').split(','))}.includes(c.id))`);
writeFileSync('bench/whole-object/run.generated.mjs',source);
await import('./run.generated.mjs?run='+Date.now());
