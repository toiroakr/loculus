import {readFileSync,writeFileSync} from 'node:fs';
const original=JSON.parse(readFileSync('bench/whole-object/bundle-results.json'));
const candidate=JSON.parse(readFileSync('bench/whole-object/candidate-bundle-results.json'));
const ids=candidate.cases.filter(c=>c.libraries.generated.consumerHash!==original.cases.find(o=>o.id===c.id).libraries.generated.consumerHash).map(c=>c.id);
writeFileSync('bench/whole-object/candidate-selection.json',JSON.stringify({ids,scope:'all profiles whose generated consumer changed; ordinary and peer code unchanged'},null,2)+'\n');
let source=readFileSync('bench/whole-object/run.generated.mjs','utf8');
source=source.replaceAll("hash('packages/rolldown/src/index.ts')","hash('bench/whole-object/array-plugin-experiment.ts')");
source=source.replace('bundles.cases.filter(c=>c.timed)',`bundles.cases.filter(c=>c.timed&&${JSON.stringify(ids)}.includes(c.id))`);
source=source.replaceAll('bench/whole-object/generated/','bench/whole-object/generated/candidate/');
for(const name of ['bundle-results','fixtures','timed-fixtures','settled-results','settled-results.partial'])source=source.replaceAll('bench/whole-object/'+name+'.json','bench/whole-object/candidate-'+name+'.json');
source=source.replaceAll("'/ ${passes}'","'/ 11'");
writeFileSync('bench/whole-object/run-candidate.generated.mjs',source);
console.log('Remeasuring changed consumers:',ids.join(', '));
await import('./run-candidate.generated.mjs');
